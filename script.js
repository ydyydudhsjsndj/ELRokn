let language = "ar";
let activeCategory = "all";
const intro = document.getElementById("intro");
const siteShell = document.getElementById("siteShell");
const grid = document.getElementById("foodGrid");
const categoryNav = document.getElementById("categoryNav");
const searchInput = document.getElementById("searchInput");

function t(key) { return translations[language][key]; }

function applyLanguage() {
  const dict = translations[language];
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined && typeof dict[key] === "string") el.innerHTML = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.placeholder = dict[key];
  });
  document.getElementById("languageSwitch").innerHTML = language === "ar" ? 'English <span aria-hidden="true">↗</span>' : 'العربية <span aria-hidden="true">↗</span>';
  document.getElementById("languageSwitch").setAttribute("aria-label", language === "ar" ? "Switch to English" : "التبديل إلى العربية");
  searchInput.setAttribute("aria-label", dict.searchPlaceholder);
  renderCategories();
  renderItems();
}

function renderCategories() {
  const categories = translations[language].categories;
  categoryNav.innerHTML = Object.entries(categories).map(([key, label]) =>
    `<button type="button" class="category-button ${activeCategory === key ? "active" : ""}" data-category="${key}" aria-pressed="${activeCategory === key}">${label}</button>`
  ).join("");
  categoryNav.querySelectorAll("button").forEach(btn => {
    btn.addEventListener("click", () => {
      activeCategory = btn.dataset.category;
      renderCategories();
      renderItems();
    });
  });
}

function renderItems() {
  const dict = translations[language];
  const query = searchInput.value.trim().toLocaleLowerCase();
  const filtered = dict.items.filter(item => {
    const matchesCategory = activeCategory === "all" || item[2] === activeCategory;
    const searchable = `${item[0]} ${item[1]} ${item[4]}`.toLocaleLowerCase();
    return matchesCategory && searchable.includes(query);
  });
  grid.innerHTML = filtered.map(item => {
    const [name, description, category, price, badge, photo] = item;
    const imageUrl = `https://images.unsplash.com/${photo}?auto=format&fit=crop&w=720&q=78`;
    return `<article class="food-card">
      <div class="food-image-wrap">
        <img class="food-image" src="${imageUrl}" alt="${escapeHTML(name)}" loading="lazy" decoding="async">
        ${badge ? `<span class="food-badge">${escapeHTML(badge)}</span>` : ""}
      </div>
      <div class="food-info">
        <div class="food-title-row"><h3 class="food-title">${escapeHTML(name)}</h3></div>
        <p class="food-description">${escapeHTML(description)}</p>
        <div class="food-price">${price} <small>${dict.currency}</small></div>
      </div>
    </article>`;
  }).join("");
  document.getElementById("resultsCount").textContent = dict.count(filtered.length);
  document.getElementById("emptyState").hidden = filtered.length !== 0;
}

function escapeHTML(value) {
  return String(value).replace(/[&<>"']/g, char => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  })[char]);
}

document.getElementById("languageSwitch").addEventListener("click", () => {
  language = language === "ar" ? "en" : "ar";
  applyLanguage();
});
searchInput.addEventListener("input", renderItems);
document.getElementById("year").textContent = new Date().getFullYear();

function openMenu() {
  intro.classList.add("is-hidden");
  siteShell.classList.add("is-visible");
  window.setTimeout(() => { intro.hidden = true; }, 800);
}
document.getElementById("skipIntro").addEventListener("click", openMenu);
applyLanguage();
// Keep intro purposeful and short; don't make users wait for every remote image.
window.setTimeout(openMenu, 2600);
